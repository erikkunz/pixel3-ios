#!/usr/bin/env python3
"""Generate an 8x16 bitmap font header (ASCII 0x20-0x7e) from a monospace TTF.

Usage: gen_font.py FONT.ttf OUT.h
Only needed when changing the font; the generated header is checked in.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16


def main():
    font = ImageFont.truetype(sys.argv[1], 13)
    rows = []
    for code in range(0x20, 0x7f):
        img = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(img)
        ch = chr(code)
        # centre the glyph horizontally, baseline near the bottom
        l, t, r, b = d.textbbox((0, 0), ch, font=font)
        x = (W - (r - l)) // 2 - l
        d.text((x, 0), ch, fill=255, font=font)
        bits = []
        for y in range(H):
            v = 0
            for xx in range(W):
                if img.getpixel((xx, y)) >= 110:
                    v |= 0x80 >> xx
            bits.append(v)
        rows.append(bits)
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/gen_font.py from %s (DejaVu fonts license). */\n"
                % sys.argv[1].rsplit("/", 1)[-1])
        f.write("#pragma once\nstatic const unsigned char font8x16[95][16] = {\n")
        for code, bits in zip(range(0x20, 0x7f), rows):
            f.write("\t{" + ", ".join("0x%02x" % b for b in bits) + "},\t/* %r */\n" % chr(code))
        f.write("};\n")


if __name__ == "__main__":
    main()
